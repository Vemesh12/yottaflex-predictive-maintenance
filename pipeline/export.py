"""JSON and SQL exports of the generated data (problem statement Step 9).

  export/json/<table>.json   every relational table + ground truth, as an array of records
  export/json/telemetry_sample.json   first 1,000 readings (full telemetry stays in Parquet:
                                      2.16M readings as JSON would be ~400 MB)
  export/sql/seed.sql        schema + INSERT statements for every relational table, then one
                             statement that loads telemetry from the Parquet files.
                             Run it from the data folder: duckdb plant.duckdb < export/sql/seed.sql
"""
from __future__ import annotations

import math
from datetime import date
from pathlib import Path

import pandas as pd
import pyarrow.parquet as pq

from .io import _iso
from .load import LOAD_ORDER, SCHEMA

BATCH = 500


def _plain(df: pd.DataFrame) -> pd.DataFrame:
    out = df.copy()
    for col in out.columns:
        if isinstance(out[col].dtype, pd.DatetimeTZDtype):
            out[col] = _iso(out[col])
    return out


def write_json(df: pd.DataFrame, path: Path) -> None:
    path.write_text(_plain(df).to_json(orient="records", indent=1, force_ascii=False) + "\n",
                    encoding="utf-8")


def _sql_literal(v) -> str:
    if v is None or (isinstance(v, float) and math.isnan(v)) or v is pd.NaT:
        return "NULL"
    if isinstance(v, (bool,)):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return repr(v)
    if isinstance(v, date):
        return f"'{v.isoformat()}'"
    return "'" + str(v).replace("'", "''") + "'"


def write_sql(tables_by_file: dict[str, pd.DataFrame], path: Path) -> None:
    parts = ["-- Seed data generated by `python -m pipeline generate` (DuckDB SQL).",
             "-- Run from the data folder so the telemetry path below resolves.", "",
             SCHEMA.read_text(encoding="utf-8")]
    for table, file in LOAD_ORDER:
        df = _plain(tables_by_file[file]).astype(object).where(lambda d: d.notna(), None)
        cols = ", ".join(df.columns)
        rows = [f"({', '.join(_sql_literal(v) for v in row)})" for row in df.itertuples(index=False)]
        for i in range(0, len(rows), BATCH):
            parts.append(f"INSERT INTO {table} ({cols}) VALUES\n" + ",\n".join(rows[i:i + BATCH]) + ";")
    parts.append("INSERT INTO telemetry_event BY NAME SELECT * FROM read_parquet('telemetry/*.parquet');\n")
    path.write_text("\n".join(parts), encoding="utf-8")


def export_all(out_dir: Path, tables_by_file: dict[str, pd.DataFrame], ground_truth: pd.DataFrame) -> dict:
    """Write JSON + SQL exports. Returns {relative path: row count} for the manifest."""
    json_dir, sql_dir = out_dir / "export" / "json", out_dir / "export" / "sql"
    json_dir.mkdir(parents=True)
    sql_dir.mkdir(parents=True)
    written = {}
    for file, df in tables_by_file.items():
        name = file.replace(".csv", ".json")
        write_json(df, json_dir / name)
        written[f"export/json/{name}"] = len(df)
    write_json(ground_truth, json_dir / "ground_truth.json")
    written["export/json/ground_truth.json"] = len(ground_truth)

    first = sorted((out_dir / "telemetry").glob("*.parquet"))[0]
    sample = pq.ParquetFile(first).read_row_group(0).slice(0, 1000).to_pandas()
    write_json(sample, json_dir / "telemetry_sample.json")
    written["export/json/telemetry_sample.json"] = len(sample)

    write_sql(tables_by_file, sql_dir / "seed.sql")
    written["export/sql/seed.sql"] = None
    return written
